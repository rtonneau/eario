//! Model Context Protocol server of an Eario application.
//!
//! [`router`] returns an HTTP route, `/mcp`, speaking the Streamable HTTP
//! transport of MCP. The runtime mounts it behind the same host, origin and
//! session-token checks as the rest of the API.
//!
//! Every tool is read-only and bounded: an agent can inspect the dashboard,
//! the loaded datasets and a limited window of rows, and nothing else. Tools
//! call the application services of [`eario_runtime::App`]; no logic is
//! duplicated here.

use std::sync::Arc;

use axum::Router;
use eario_core::{ComponentId, DatasetId};
use eario_data::query;
use eario_runtime::{App, AppError};
use rmcp::handler::server::router::tool::ToolRouter;
use rmcp::handler::server::wrapper::Parameters;
use rmcp::model::{ErrorData, Implementation, ServerCapabilities, ServerConfig};
use rmcp::transport::streamable_http_server::session::local::LocalSessionManager;
use rmcp::transport::streamable_http_server::{StreamableHttpServerConfig, StreamableHttpService};
use rmcp::{ServerHandler, schemars, tool, tool_handler, tool_router};
use serde::{Deserialize, Serialize};

/// Largest number of rows `preview_dataset` returns in one call.
pub const MAX_PREVIEW_ROWS: u32 = 100;

const INSTRUCTIONS: &str = "Read-only access to a running Eario dashboard application. \
     Start with describe_dashboard and list_datasets. Row access is paginated: \
     preview_dataset returns at most 100 rows per call.";

/// Builds the `/mcp` route serving `app`.
///
/// Pass the result to
/// [`ServerConfig::extra_routes`](eario_runtime::ServerConfig::extra_routes).
pub fn router(app: App) -> Router {
    // Stateless request/response: no session to track and no long-lived
    // stream that would delay the shutdown of the application.
    let config = StreamableHttpServerConfig::default()
        .with_legacy_session_mode(false)
        .with_json_response(true)
        .with_sse_keep_alive(None);
    let service = StreamableHttpService::new(
        move || Ok(EarioTools::new(app.clone())),
        Arc::new(LocalSessionManager::default()),
        config,
    );
    Router::new().nest_service("/mcp", service)
}

/// The MCP tools of one application.
#[derive(Clone)]
struct EarioTools {
    app: App,
    #[expect(dead_code, reason = "read by the code generated by #[tool_handler]")]
    tool_router: ToolRouter<Self>,
}

/// Summary of one component, as returned by `describe_dashboard`.
#[derive(Serialize)]
struct ComponentSummary<'a> {
    id: &'a str,
    title: Option<&'a str>,
    definition: &'a eario_core::ComponentKind,
}

/// Summary of one page, as returned by `describe_dashboard`.
#[derive(Serialize)]
struct PageSummary<'a> {
    id: &'a str,
    title: &'a str,
    components: Vec<ComponentSummary<'a>>,
}

/// Arguments of `preview_dataset`.
#[derive(Debug, Deserialize, schemars::JsonSchema)]
struct PreviewRequest {
    /// Identifier of the dataset, as returned by list_datasets.
    dataset_id: String,
    /// Position of the first row to return. Defaults to 0.
    #[serde(default)]
    offset: u32,
    /// Number of rows to return, at most 100. Defaults to 20.
    limit: Option<u32>,
}

/// Arguments of the tools that take only a dataset.
#[derive(Debug, Deserialize, schemars::JsonSchema)]
struct DatasetRequest {
    /// Identifier of the dataset, as returned by list_datasets.
    dataset_id: String,
}

/// Arguments of `get_component_data`.
#[derive(Debug, Deserialize, schemars::JsonSchema)]
struct ComponentRequest {
    /// Identifier of the component, as returned by describe_dashboard.
    component_id: String,
    /// For tables, position of the first row of the page. Defaults to 0.
    #[serde(default)]
    offset: u32,
}

fn to_json(value: &impl Serialize) -> Result<String, ErrorData> {
    serde_json::to_string_pretty(value)
        .map_err(|error| ErrorData::internal_error(error.to_string(), None))
}

fn tool_error(error: AppError) -> ErrorData {
    ErrorData::invalid_params(error.to_string(), None)
}

/// Runs a CPU-bound service call off the asynchronous runtime.
async fn blocking<T, F>(call: F) -> Result<T, ErrorData>
where
    T: Send + 'static,
    F: FnOnce() -> Result<T, AppError> + Send + 'static,
{
    match tokio::task::spawn_blocking(call).await {
        Ok(result) => result.map_err(tool_error),
        Err(error) => Err(ErrorData::internal_error(error.to_string(), None)),
    }
}

#[tool_router]
impl EarioTools {
    fn new(app: App) -> Self {
        Self { app, tool_router: Self::tool_router() }
    }

    #[tool(
        description = "Describe the dashboard: its title, pages and components, with the \
                       dataset and state each component is bound to, and the current state.",
        annotations(read_only_hint = true)
    )]
    fn describe_dashboard(&self) -> Result<String, ErrorData> {
        let info = self.app.info();
        let pages: Vec<PageSummary<'_>> = info
            .spec
            .pages
            .iter()
            .map(|page| PageSummary {
                id: &page.id,
                title: &page.title,
                components: page
                    .rows
                    .iter()
                    .flat_map(|row| &row.items)
                    .map(|component| ComponentSummary {
                        id: component.id.as_str(),
                        title: component.title.as_deref(),
                        definition: &component.kind,
                    })
                    .collect(),
            })
            .collect();
        to_json(&serde_json::json!({
            "title": info.spec.title,
            "eario_version": info.eario_version,
            "pages": pages,
            "state": info.state,
        }))
    }

    #[tool(
        description = "List the loaded datasets with their source, row count, worksheets and \
                       columns (name, type and number of missing values).",
        annotations(read_only_hint = true)
    )]
    fn list_datasets(&self) -> Result<String, ErrorData> {
        to_json(&self.app.datasets())
    }

    #[tool(
        description = "Return a window of rows of a dataset, unfiltered. At most 100 rows per \
                       call; use offset to page through the dataset.",
        annotations(read_only_hint = true)
    )]
    async fn preview_dataset(
        &self,
        Parameters(request): Parameters<PreviewRequest>,
    ) -> Result<String, ErrorData> {
        let app = self.app.clone();
        let limit = request.limit.unwrap_or(20).min(MAX_PREVIEW_ROWS);
        let page = blocking(move || {
            let frame = app.dataset_frame(&DatasetId::new(request.dataset_id))?;
            let rows = query::row_count(&frame);
            Ok(query::table_page(&frame, request.offset, limit, rows)?)
        })
        .await?;
        to_json(&page)
    }

    #[tool(
        description = "Compute descriptive statistics (count, missing, mean, standard deviation, \
                       min, median, max) of every numeric column of a dataset, unfiltered.",
        annotations(read_only_hint = true)
    )]
    async fn dataset_statistics(
        &self,
        Parameters(request): Parameters<DatasetRequest>,
    ) -> Result<String, ErrorData> {
        let app = self.app.clone();
        let stats = blocking(move || {
            let frame = app.dataset_frame(&DatasetId::new(request.dataset_id))?;
            Ok(query::statistics(&frame)?)
        })
        .await?;
        to_json(&stats)
    }

    #[tool(
        description = "Return what a dashboard component currently shows, with the user's \
                       filter and selections applied: table page, chart points or statistics.",
        annotations(read_only_hint = true)
    )]
    async fn get_component_data(
        &self,
        Parameters(request): Parameters<ComponentRequest>,
    ) -> Result<String, ErrorData> {
        let app = self.app.clone();
        let data = blocking(move || {
            app.component_data(&ComponentId::new(request.component_id), request.offset)
        })
        .await?;
        to_json(&data)
    }
}

#[tool_handler]
impl ServerHandler for EarioTools {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build())
            .with_server_info(Implementation::new("eario", env!("CARGO_PKG_VERSION")))
            .with_instructions(INSTRUCTIONS)
    }
}
